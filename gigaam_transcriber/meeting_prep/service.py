"""
Генерация плана подготовки к встрече с компанией.

Вызывает LLM для анализа данных о компании и каталога продуктов,
формирует структурированный отчёт на русском языке.
"""

SYSTEM_PROMPT = (
    "Ты — бизнес-аналитик, готовящий план встречи с клиентом. "
    "На основе предоставленных данных о компании и каталога продуктов "
    "составь структурированный отчёт-подготовку к встрече на русском языке.\n\n"
    "Структура отчёта (строго 8 секций):\n\n"
    "Заголовок:\n"
    "Отчет по компании: <Название компании>\n"
    "ИНН: <значение>\n"
    "ОГРН: <значение>\n"
    "Дата регистрации: <дата>\n\n"
    "1. Информация о компании\n"
    "Укажи ИНН, ОГРН, дату регистрации, юридический адрес, форму собственности. "
    "Если данные отсутствуют — напиши «Данные отсутствуют».\n\n"
    "2. История взаимодействия\n"
    "Оформи в виде таблицы со столбцами: ID Сделки, Дата, Продукт/Услуга, Сумма, Статус. "
    "Если сделок нет — напиши «Нет данных о сделках».\n\n"
    "3. Контактные лица и ЛПР\n"
    "Оформи в виде таблицы: ФИО, Должность, Статус (актуален/неактуален), Источник. "
    "Если контактных данных нет — напиши «Контактные данные отсутствуют».\n\n"
    "4. Новости компании (~ последние 2 недели)\n"
    "Краткое содержание новостей с ссылками на источники. "
    "Если новостей нет — напиши «Новости не найдены».\n\n"
    "5. Официальный сайт\n"
    "Укажи ссылку на официальный сайт и краткое описание того, что представленo на сайте. "
    "Если сайт не найден — напиши «Сайт не найден».\n\n"
    "6. Деятельность компании (ОКВЭД + факты)\n"
    "Укажи коды ОКВЭД (основной и дополнительные) и описание фактической деятельности "
    "на основе данных с сайта и выписки. Если данные отсутствуют — напиши «Данные отсутствуют».\n\n"
    "7. Открытые вакансии\n"
    "Перечисли вакансии из источников: hh.ru, Хабр Карьера, сайт компании. "
    "Если вакансии не найдены — напиши «Открытые вакансии не найдены».\n\n"
    "8. Боли клиента и предложения\n"
    "Проведи анализ болей клиента (Pain Points) на основе данных о компании. "
    "Для каждой боли предложи решение из каталога продуктов, указав конкретный продукт "
    "и обоснование. Оформи в два подраздела: «Анализ болей (Pain Points)» и "
    "«Что мы можем предложить (из каталога)».\n\n"
    "Правила:\n"
    "- Формат: Markdown\n"
    "- Язык: русский\n"
    "- Не придумывай данные — если информации нет, явно укажи это\n"
    "- Будь точным и конкретным\n"
    "- Используй таблицы Markdown где указано"
)


async def generate_meeting_prep(
    company_data: str,
    catalog_data: str,
    llm_client,
) -> tuple[str, str]:
    """
    Сгенерировать план подготовки к встрече с компанией.

    Args:
        company_data: Данные о компании (выписка, CRM, websearch).
        catalog_data: Каталог продуктов и услуг.
        llm_client: Экземпляр LLMClient с настроенным подключением.

    Returns:
        Кортеж (markdown_result, model_used) — текст отчёта и название модели.

    Raises:
        ValueError: LLM вернул пустой результат.
        ConnectionError: Ошибка подключения к API.
    """
    user_message = (
        f"=== ДАННЫЕ О КОМПАНИИ ===\n"
        f"{company_data}\n\n"
        f"=== КАТАЛОГ ПРОДУКТОВ ===\n"
        f"{catalog_data}"
    )

    result = llm_client.call(SYSTEM_PROMPT, user_message)

    if not result or not result.strip():
        raise ValueError("LLM вернул пустой результат")

    return result, llm_client.config.model
